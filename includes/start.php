<?php
/**
 * Starts Zinn® Chat: every part of it, the AI core, and its start-up hooks.
 *
 * Read by bootstrap.php through Cli_Start::start(): at once, or — in a WP-CLI command — on WP-CLI's
 * `after_wp_load`, with every already-fired action replayed (class-cli-start.php, stage PERF3).
 *
 * ⛔ Explicit `require_once __DIR__ . '…'` lines, never a constant-built path:
 * `scripts/wp-class-loader-check.py` reads these lines statically to prove that every class the
 * plugin calls is in a file it loads, and a path built at run time is invisible to it.
 *
 * @package ZinnDigital\ZinnChat
 */

declare( strict_types = 1 );

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

require_once __DIR__ . '/ai-core/load.php';

// AI agents (MCP, lane PLUGIN-MCP, docs/901): every staff action as a WordPress ability, through
// the shared MCP kit (wp/packages/zinn-mcp-kit) and the bundled WordPress MCP adapter.
require_once __DIR__ . '/mcp-kit/load.php';
\ZinnDigital\ZinnChat\Mcp\Abilities::boot();
// Generated by wp/bin/build-updater.php; the WordPress.org build removes this line and the file.
require_once __DIR__ . '/class-zinn-chat-updater.php';
// The shared Zinn® panel in wp-admin. GENERATED by wp/bin/build-promo.php.
require_once __DIR__ . '/class-zinn-chat-promo.php';

\ZinnDigital\ZinnChat\AiCore\Core::boot(
	array(
		'slug' => 'zinn-chat',
		'name' => 'Zinn® Chat',
		'pro'  => static function (): bool {
			return \ZinnDigital\ZinnChat\Plugin::is_pro();
		},
	)
);

\ZinnDigital\ZinnChat\Plugin::init();
add_action( 'plugins_loaded', array( 'Zinn_Chat_Promo', 'register' ) );

// HOSTDISC (docs/894): the hosting-customer Pro discount card, on this plugin's own screens, only
// on a site Zinn hosts, and never once Zinn® Chat Pro is in use. Generated (`wp/bin/build-promo.php`)
// and global, so it is required and named by STRING, like the promo panel.
require_once __DIR__ . '/class-zinn-chat-pro-discount.php';
add_action(
	'plugins_loaded',
	static function (): void {
		\Zinn_Chat_Pro_Discount::register( 'zinn-chat', '\\ZinnDigital\\ZinnChat\\Plugin::is_pro' );
	}
);
